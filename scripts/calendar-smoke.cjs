const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.ORCA_PLAYWRIGHT_MODULE || 'playwright');
const fixture = require('./redesign-fixture.cjs');
const dist = path.resolve('web/dist');
const server = http.createServer((req, res) => {
  let file = path.resolve(dist, '.' + new URL(req.url, 'http://localhost').pathname);
  if (!file.startsWith(dist + path.sep)) file = path.join(dist, 'index.html');
  if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(dist, 'index.html');
  res.setHeader('Content-Type', ({'.html':'text/html','.js':'application/javascript','.css':'text/css'})[path.extname(file)] || 'application/octet-stream');
  res.end(fs.readFileSync(file));
});
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Jakarta' });
    const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
    const state = fixture.createFixture();
    const now = new Date(), y = now.getFullYear(), m = String(now.getMonth()+1).padStart(2,'0'), d = String(now.getDate()).padStart(2,'0'); const today = `${y}-${m}-${d}`;
    state.spaces.push({ ...state.spaces[0], id: 'space-b', name: 'Personal', slug: 'personal' });
    state.tasks[0].planned_date = today; state.tasks[1].due_date = today; state.tasks[1].space_id = 'space-b';
    state.events = [{ id: 'event-a', title: 'Morning meeting', space_id: state.spaces[0].id, start_at: `${today}T09:00:00+07:00`, end_at: `${today}T10:00:00+07:00`, is_all_day: false }, { id: 'event-b', title: 'Personal meeting', space_id: 'space-b', start_at: `${today}T09:30:00+07:00`, end_at: `${today}T11:00:00+07:00`, is_all_day: false }];
    await fixture.connect(page, state);
    let eventReads = 0; page.on('request', req => { if (req.method()==='GET' && new URL(req.url()).pathname.endsWith('/events')) eventReads++; });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.locator('#auth-email').fill('qa@example.invalid'); await page.locator('#auth-password').fill('qa-only-password'); await page.locator('form button[type=submit]').click();
    await page.getByRole('button', { name: 'Calendar', exact: true }).click();
    const calendar = page.locator('.calendar-workspace');
    await calendar.getByRole('button', { name: 'Personal', exact: true }).waitFor();
    await calendar.locator('.calendar-time-day').last().waitFor();
    assert.equal(await calendar.locator('.calendar-time-day').count(), 7);
    assert.equal(await calendar.locator('.calendar-item').filter({ hasText:'Morning meeting' }).count(), 1);
    assert.equal(await calendar.locator('.calendar-item').filter({ hasText:'Explore the visual identity' }).count(), 1);
    const initialLabel = await calendar.locator('.calendar-period').innerText();
    await calendar.getByRole('button',{name:'Next period'}).click();
    assert.notEqual(await calendar.locator('.calendar-period').innerText(), initialLabel);
    assert.equal(await calendar.locator('.calendar-item').filter({hasText:'Morning meeting'}).count(),0);
    await calendar.getByRole('button',{name:'Previous period'}).click(); assert.equal(await calendar.locator('.calendar-period').innerText(),initialLabel);
    await calendar.getByRole('button',{name:'Studio',exact:true}).click();
    assert.equal(await calendar.locator('.calendar-item').filter({hasText:'Personal meeting'}).count(),0);
    await calendar.getByRole('button',{name:'Personal',exact:true}).click();
    assert.equal(await calendar.locator('.calendar-item').filter({hasText:'Personal meeting'}).count(),1);
    assert.equal(await calendar.locator('.calendar-item').filter({hasText:'Morning meeting'}).count(),0);
    await calendar.getByRole('button',{name:'All Spaces',exact:true}).click();
    await calendar.getByRole('button',{name:'Month',exact:true}).click(); assert.equal(await calendar.locator('.calendar-month-day').count(),42);
    await calendar.getByRole('button',{name:'Day',exact:true}).click(); assert.equal(await calendar.locator('.calendar-time-day').count(),1);
    await calendar.getByRole('button',{name:'Next period'}).click(); await calendar.getByRole('button',{name:'Today',exact:true}).click();
    assert.equal(await calendar.locator('.calendar-time-day').getAttribute('data-date'),today);
    await calendar.getByRole('button',{name:'Timeline',exact:true}).click(); assert.equal(await calendar.locator('.calendar-timeline > section').count(),7);
    assert.equal(await calendar.locator('.calendar-timeline .calendar-item').filter({hasText:'Review the tasting menu'}).count(),1);
    await calendar.getByRole('button',{name:'Add Event',exact:true}).click();
    await page.getByLabel('EVENT TITLE',{exact:true}).fill('New dated event'); await page.getByLabel('DATE',{exact:true}).fill(today);
    await page.getByLabel('START TIME',{exact:true}).fill('00:00'); await page.getByLabel('END TIME',{exact:true}).fill('00:30');
    await page.getByRole('button',{name:'Book Event',exact:true}).click(); await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.match(state.events.at(-1).start_at,/T17:00:00.000Z$/);
    await calendar.getByRole('button',{name:'Refresh events',exact:true}).click();
    await page.waitForFunction(() => !document.querySelector('.calendar-layout')?.getAttribute('aria-busy') || document.querySelector('.calendar-layout').getAttribute('aria-busy')==='false');
    assert.equal(await calendar.locator('.calendar-item').filter({hasText:'New dated event'}).count(),1);
    assert.equal(eventReads,2,'filters must not cause repeat fetching');
    await page.route('**/api/v1/events', async route => {
      if (route.request().method() === 'GET') await route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Calendar temporarily unavailable'})});
      else await route.fallback();
    });
    await calendar.getByRole('button',{name:'Refresh events',exact:true}).click();
    await calendar.getByRole('alert').waitFor();
    await page.unroute('**/api/v1/events');
    await calendar.getByRole('button',{name:'Retry',exact:true}).click();
    await calendar.getByRole('alert').waitFor({state:'hidden'});
    await calendar.getByRole('button',{name:'Week',exact:true}).click();
    await page.screenshot({path:'bin/calendar-desktop.png',fullPage:true});
    await page.setViewportSize({width:360,height:800});
    await calendar.getByRole('button',{name:'Day',exact:true}).click();
    assert.ok(await calendar.getByRole('button',{name:'Today',exact:true}).isVisible());
    const dayBounds = await calendar.locator('.calendar-matrix').boundingBox(); assert.ok(dayBounds.width <= 360);
    await page.screenshot({path:'bin/calendar-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('Calendar browser checks passed: four views, date navigation, cross-space filtering, real-task projection, event creation/refresh, no reactive refetch loop, mobile layout.');
  } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); server.close(); process.exitCode=1; });
